//! K1's cutoff walk: app/live_cutoff.c is generated from the firmware's own cutoff curve
//! (`sid_cutoff_hz`). SIDOU_CUTOFF_TABLE_UPDATE=1 rewrites it.

use std::path::PathBuf;

use sidou_sys::{
    live_cutoff_down, live_cutoff_steps, live_cutoff_up, sid_cutoff_hz, LIVE_CUTOFF_STEPS,
};

const STEPS: usize = LIVE_CUTOFF_STEPS as usize;
const REGS: usize = 2048;

fn curve(model: u32) -> Vec<f64> {
    (0..REGS as u32)
        .map(|r| f64::from(unsafe { sid_cutoff_hz(model, 0, r) }))
        .collect()
}

struct Walk {
    steps: [u16; STEPS],
    up: [i8; 64],
    down: [i8; 64],
}

fn walk(model: u32) -> Walk {
    let hz = curve(model);
    let floor = hz[0] * 2f64.powf(1.0 / 12.0);
    let r0 = hz.iter().position(|&h| h >= floor).unwrap();
    let f_lo = hz[r0];
    let f_hi = hz.iter().cloned().fold(0.0, f64::max);
    let mut steps = [0u16; STEPS];
    steps[0] = r0 as u16;
    for i in 1..STEPS {
        let prev = usize::from(steps[i - 1]);
        let target = if i == STEPS - 1 {
            f_hi
        } else {
            f_lo * (f_hi / f_lo).powf(i as f64 / (STEPS - 1) as f64)
        };
        steps[i] = (prev + 1..REGS)
            .find(|&r| hz[r] >= target && hz[r] > hz[prev])
            .unwrap_or(REGS - 1) as u16;
    }
    let mut up = [0i8; 64];
    let mut down = [0i8; 64];
    for b in 0..64usize {
        up[b] = steps
            .iter()
            .position(|&e| usize::from(e) > b * 32 + 31)
            .unwrap_or(STEPS) as i8;
        down[b] = steps
            .iter()
            .rposition(|&e| usize::from(e) < b * 32)
            .map_or(-1, |i| i as i8);
    }
    Walk { steps, up, down }
}

// The generated file's own licence header; reuse must not read it as this file's.
// REUSE-IgnoreStart
fn source() -> String {
    let w = [walk(0), walk(1)];
    let mut s = String::from(
        "// SPDX-FileCopyrightText: 2026 SIDOU contributors\n\
         // SPDX-License-Identifier: GPL-3.0-or-later\n\
         /* Generated by host/crates/sidou-tests/tests/app/live_cutoff.rs; do not edit.\n \
         * K1's walk (live.h): per chip model, 65 registers evenly spaced in pitch from a semitone\n \
         * above the chip's lowest cutoff to its highest, then, per bucket of 32 registers, the\n \
         * first entry above it and the last entry below it. */\n\
         #include \"live.h\"\n\n\
         const uint16_t live_cutoff_steps[2][LIVE_CUTOFF_STEPS] = {\n",
    );
    for m in &w {
        s.push_str("    {\n");
        for row in m.steps.chunks(13) {
            let v: Vec<String> = row.iter().map(|e| format!("{e},")).collect();
            s.push_str(&format!("        {}\n", v.join(" ")));
        }
        s.push_str("    },\n");
    }
    s.push_str("};\n");
    for (name, pick) in [("up", 0), ("down", 1)] {
        s.push_str(&format!("\nconst int8_t live_cutoff_{name}[2][64] = {{\n"));
        for m in &w {
            s.push_str("    {\n");
            let t = if pick == 0 { &m.up } else { &m.down };
            for row in t.chunks(16) {
                let v: Vec<String> = row.iter().map(|e| format!("{e},")).collect();
                s.push_str(&format!("        {}\n", v.join(" ")));
            }
            s.push_str("    },\n");
        }
        s.push_str("};\n");
    }
    s
}
// REUSE-IgnoreEnd

fn cents(a: f64, b: f64) -> f64 {
    1200.0 * (b / a).log2()
}

#[test]
fn the_cutoff_table_is_generated_and_rises() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../app/live_cutoff.c");
    let want = source();
    if std::env::var("SIDOU_CUTOFF_TABLE_UPDATE").as_deref() == Ok("1") {
        std::fs::write(&path, &want).unwrap();
        return;
    }
    let got = std::fs::read_to_string(&path).unwrap();
    assert!(
        got == want,
        "{} is stale; rerun with SIDOU_CUTOFF_TABLE_UPDATE=1",
        path.display()
    );
    for m in 0..2usize {
        let hz = curve(m as u32);
        let t = unsafe { live_cutoff_steps }[m];
        let up = unsafe { live_cutoff_up }[m];
        let down = unsafe { live_cutoff_down }[m];
        let lowest = hz[0] * 2f64.powf(1.0 / 12.0);
        assert!(
            hz[usize::from(t[0])] >= lowest,
            "model {m}: starts a semitone up"
        );
        assert!(
            hz[usize::from(t[0]) - 1] < lowest,
            "model {m}: the first such register"
        );
        let top = hz.iter().cloned().fold(0.0, f64::max);
        assert_eq!(
            hz[usize::from(t[STEPS - 1])],
            top,
            "model {m}: ends on the highest"
        );
        for i in 1..STEPS {
            let (a, b) = (usize::from(t[i - 1]), usize::from(t[i]));
            assert!(b > a, "model {m}: registers rise at {i}");
            assert!(hz[b] > hz[a], "model {m}: Hz rise at {i}");
            let c = cents(hz[a], hz[b]);
            // The 6581's range is 6.8 octaves, 64 steps of about 128 cents. The 8580's is 11
            // octaves (6.8 Hz to 14.3 kHz): its steps are about 207 cents, and its first 29
            // entries are single registers (the chip's own resolution, coarse at the bottom).
            let (lo, hi) = if m == 0 { (40.0, 160.0) } else { (40.0, 230.0) };
            assert!(
                (lo..=hi).contains(&c) || (m == 1 && b == a + 1),
                "model {m}: step {i} is {c:.0} cents ({a} -> {b})"
            );
        }
        for b in 0..64usize {
            let (lo, hi) = (b * 32, b * 32 + 31);
            let u = up[b];
            assert!(
                u == STEPS as i8 || usize::from(t[u as usize]) > hi,
                "up {b}"
            );
            assert!(
                u == 0 || usize::from(t[u as usize - 1]) <= hi,
                "up {b} is the first"
            );
            let d = down[b];
            assert!(d == -1 || usize::from(t[d as usize]) < lo, "down {b}");
            assert!(
                d == STEPS as i8 - 1 || usize::from(t[(d + 1) as usize]) >= lo,
                "down {b} is the last"
            );
        }
    }
}
