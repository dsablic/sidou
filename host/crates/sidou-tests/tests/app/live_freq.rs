//! The PAL note-frequency tables: app/live_freq.c is generated from the formulas here.
//! SIDOU_FREQ_TABLE_UPDATE=1 rewrites it. Also the pitch between the notes (live_freq_at),
//! which pitch bend and vibrato play.

use std::path::PathBuf;

use crate::freq_table;
use sidou_sys::{live_freq_at, live_freq_fine_q20, live_freq_top_q4, SID_CLOCK_PAL};

/// One semitone of live_freq_at's offset.
const SEMITONE: i32 = 8192;
/// The highest note that fits 16 bits, and the first of the top octave.
const TOP: i32 = 106;
const TOP_FIRST: i32 = 95;

/// f * 2^24 / clock for MIDI note n, unrounded.
fn exact(n: i32) -> f64 {
    exact_at(f64::from(n))
}

/// The same for a pitch between the notes.
fn exact_at(n: f64) -> f64 {
    let f = 440.0 * 2f64.powf((n - 69.0) / 12.0);
    f * f64::from(1u32 << 24) / f64::from(SID_CLOCK_PAL)
}

/// The top octave in 1/16ths, unrounded.
fn top_q4_exact(i: i32) -> f64 {
    exact(TOP_FIRST + i) * 16.0
}

/// 2^20 * (2^(j / 768) - 1): 1/64 semitone steps, unrounded.
fn fine_q20_exact(j: i32) -> f64 {
    f64::from(1u32 << 20) * (2f64.powf(f64::from(j) / 768.0) - 1.0)
}

fn freq_at(note: u8, offset: i32) -> u16 {
    unsafe { live_freq_at(note, offset) }
}

/// The register value for note n: rounded, folded down by octaves until it fits 16 bits.
fn expected(n: i32) -> u16 {
    let mut m = n;
    while exact(m).round() > f64::from(u16::MAX) {
        m -= 12;
    }
    exact(m).round() as u16
}

// The generated file's own licence header; reuse must not read it as this file's.
// REUSE-IgnoreStart
fn source() -> String {
    let mut s = String::from(
        "// SPDX-FileCopyrightText: 2026 SIDOU contributors\n\
         // SPDX-License-Identifier: GPL-3.0-or-later\n\
         /* Generated by host/crates/sidou-tests/tests/app/live_freq.rs; do not edit.\n \
         * round(f * 2^24 / 985248) for MIDI notes 0..127, f = 440 * 2^((n - 69) / 12);\n \
         * notes above 106 are folded down by octaves to fit 16 bits. Then the two tables\n \
         * live_freq_at moves between the notes with. */\n\
         #include \"live.h\"\n\n\
         const uint16_t live_freq_table[128] = {\n",
    );
    for row in 0..16 {
        s.push_str("   ");
        for n in row * 8..row * 8 + 8 {
            s.push_str(&format!(" 0x{:04x},", expected(n)));
        }
        s.push_str(&format!(" /* {}..{} */\n", row * 8, row * 8 + 7));
    }
    s.push_str("};\n\n");
    s.push_str(
        "/* Notes 95..106 in 1/16ths: round(f * 2^24 / 985248 * 16). */\n\
         const uint32_t live_freq_top_q4[12] = {\n",
    );
    for row in 0..2 {
        s.push_str("   ");
        for i in row * 6..row * 6 + 6 {
            s.push_str(&format!(" {},", top_q4_exact(i).round() as u32));
        }
        s.push('\n');
    }
    s.push_str(
        "};\n\n\
         /* round(2^20 * 2^(j / 768)) - 2^20: 1/64 semitone steps, j = 0..64. */\n\
         const uint32_t live_freq_fine_q20[65] = {\n",
    );
    for row in 0..9 {
        s.push_str("   ");
        for j in (row * 8..row * 8 + 8).filter(|&j| j <= 64) {
            s.push_str(&format!(" {},", fine_q20_exact(j).round() as u32));
        }
        s.push('\n');
    }
    s.push_str("};\n");
    s
}
// REUSE-IgnoreEnd

#[test]
fn the_formula_is_far_from_rounding_ties() {
    for n in 0..128 {
        let frac = exact(n).fract();
        assert!(
            (frac - 0.5).abs() > 1e-6,
            "note {n}: {} is too close to a tie for f64 to round it reliably",
            exact(n)
        );
    }
}

#[test]
fn the_fine_tables_are_far_from_rounding_ties() {
    for i in 0..12 {
        let frac = top_q4_exact(i).fract();
        assert!((frac - 0.5).abs() > 1e-6, "top note {i}");
    }
    for j in 0..=64 {
        let frac = fine_q20_exact(j).fract();
        assert!((frac - 0.5).abs() > 1e-6, "fine step {j}");
    }
}

#[test]
fn the_fine_tables_match_their_formulas() {
    let top = unsafe { live_freq_top_q4 };
    let fine = unsafe { live_freq_fine_q20 };
    for i in 0..12 {
        assert_eq!(f64::from(top[i as usize]), top_q4_exact(i).round(), "{i}");
    }
    for j in 0..=64 {
        assert_eq!(
            f64::from(fine[j as usize]),
            fine_q20_exact(j).round(),
            "{j}"
        );
    }
}

#[test]
fn freq_at_offset_0_is_the_table() {
    let t = freq_table();
    for n in 0..128u8 {
        assert_eq!(freq_at(n, 0), t[usize::from(n)], "note {n}");
    }
}

#[test]
fn freq_at_whole_semitones_is_the_table_note() {
    let t = freq_table();
    for n in 0..=TOP as u8 {
        for k in -3..=3i32 {
            let m = i32::from(n) + k;
            if (0..=TOP).contains(&m) {
                assert_eq!(freq_at(n, k * SEMITONE), t[m as usize], "note {n} {k:+}");
            }
        }
    }
}

/// Every pitch the offset can reach, 1/8192 semitone apart: within 0.6 of the exact value,
/// never falling, never rising by more than 1 (the register's own resolution).
#[test]
fn freq_at_is_exact_monotone_and_smooth_across_the_range() {
    let (mut prev, mut worst, mut worst_at) = (0u16, 0.0f64, 0);
    for p in 0..=(TOP * SEMITONE + SEMITONE - 1) {
        let f = freq_at(0, p);
        let want = exact_at(f64::from(p) / f64::from(SEMITONE));
        if want <= f64::from(u16::MAX) {
            let err = (f64::from(f) - want).abs();
            if err > worst {
                (worst, worst_at) = (err, p);
            }
        } else {
            assert_eq!(f, u16::MAX, "pitch {p} saturates");
        }
        if p > 0 {
            assert!(f >= prev, "pitch {p}: {prev} -> {f}");
            assert!(f - prev <= 1, "pitch {p}: {prev} -> {f}");
        }
        prev = f;
    }
    println!("live_freq_at: worst error {worst:.3} at {worst_at}");
    assert!(worst < 0.6, "{worst} at {worst_at}");
}

#[test]
fn freq_at_offsets_from_any_note_are_the_same_pitch() {
    for n in 0..=TOP as u8 {
        for off in [-30_000, -8191, -1, 1, 4096, 8191, 8193, 100_000] {
            let p = i32::from(n) * SEMITONE + off;
            if (0..=TOP * SEMITONE).contains(&p) {
                assert_eq!(freq_at(n, off), freq_at(0, p), "note {n} {off:+}");
            }
        }
    }
}

#[test]
fn freq_at_folds_high_notes_before_bending_and_clamps_at_both_ends() {
    // Notes above 106 play their octave below (the table); a bend moves from there.
    assert_eq!(freq_at(120, 2 * SEMITONE), freq_table()[98]);
    assert_eq!(freq_at(107, -SEMITONE), freq_table()[94]);
    assert_eq!(freq_at(0, -1), freq_table()[0]);
    assert_eq!(freq_at(0, i32::MIN), freq_table()[0]);
    assert_eq!(freq_at(106, SEMITONE), u16::MAX);
    assert_eq!(freq_at(60, i32::MAX), u16::MAX);
}

/// One 14-bit bend step at the default range of +-2 semitones is 400 / 16384 cents; the
/// register's step is coarser than that at every pitch, so the bend moves by single register
/// steps: these are its sizes in cents.
#[test]
fn a_bend_step_is_finer_than_the_register() {
    let bend_step_cents = 400.0 / 16384.0;
    let t = freq_table();
    let lsb_cents = |f: u16| 1200.0 * (1.0 + 1.0 / f64::from(f)).log2();
    for n in [24usize, 36, 48, 60, 72, 84, 96, 106] {
        println!(
            "note {n}: register step {:.3} cents, bend step {bend_step_cents:.4} cents",
            lsb_cents(t[n])
        );
    }
    assert!(lsb_cents(u16::MAX) > bend_step_cents);
    assert!(
        lsb_cents(t[60]) < 0.4,
        "C4 moves in steps of under 0.4 cents"
    );
}

#[test]
fn table_matches_the_formula() {
    let t = freq_table();
    for n in 0..128 {
        assert_eq!(t[n as usize], expected(n), "note {n}");
    }
}

#[test]
fn a4_is_0x1d45() {
    assert_eq!(freq_table()[69], 0x1d45);
}

#[test]
fn note_106_is_the_highest_that_fits_unfolded() {
    let t = freq_table();
    assert_eq!(f64::from(t[106]), exact(106).round());
    assert!(exact(107).round() > f64::from(u16::MAX));
    for n in 107..128 {
        assert_eq!(t[n], t[n - 12], "note {n} folds to the octave below");
    }
}

#[test]
fn pitch_rises_through_the_unfolded_range() {
    let t = freq_table();
    assert!(t.windows(2).take(106).all(|w| w[0] < w[1]));
}

#[test]
fn generated_source_is_up_to_date() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../app/live_freq.c");
    let want = source();
    if std::env::var("SIDOU_FREQ_TABLE_UPDATE").as_deref() == Ok("1") {
        std::fs::write(&path, &want).unwrap();
        return;
    }
    let got = std::fs::read_to_string(&path).unwrap();
    assert!(
        got == want,
        "{} is stale; rerun with SIDOU_FREQ_TABLE_UPDATE=1",
        path.display()
    );
}
