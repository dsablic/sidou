//! The waveform and envelope DACs: reSIDfp's R-2R ladder model (`Dac::kinkedDac`), here
//! as a function of its 2R/R ratio (the "kink") so that it can be generated over a grid
//! and controlled live. At reSIDfp's ratio for each model it reproduces reSIDfp's tables
//! (tested against them through residfp-sys).

use std::fmt::Write;

use crate::{Generated, RESIDFP_REV};

/// reSIDfp's 2R/R ratio: the 6581's ladder is kinked, the 8580's is linear.
pub const KINK_6581: f64 = 2.20;
pub const KINK_8580: f64 = 2.00;
/// reSIDfp's MOSFET leakage: an off bit still adds this fraction of its weight.
pub const LEAKAGE_6581: f64 = 0.0075;
pub const LEAKAGE_8580: f64 = 0.0035;
/// reSIDfp's cubic saturation of the 6581's waveform DAC (Dac::getOutput).
pub const SAT_GAIN: f64 = 1.1;
pub const SAT: f64 = 1.1;
/// The waveform DAC input reSIDfp takes as the voice's zero (SID::setChipModel).
pub const ZERO_6581: u32 = 0x380;
pub const ZERO_8580: u32 = 0x800;
/// The 6581's voice DC that follows the envelope (FilterModelConfig6581: 0.2143 V per
/// envelope DAC unit), in units of its voice voltage range (1.5 V). The 8580's is
/// constant, so the mixer and the output's DC blocker take it out.
pub const VOICE_DC_6581: f64 = 0.2143 / 1.5;

/// The kink grid: reSIDfp's ratio for each model is a grid point.
pub const KINKS: [f64; 9] = [2.00, 2.05, 2.10, 2.15, 2.20, 2.25, 2.30, 2.35, 2.40];

/// The weight of each bit of a `bits`-bit R-2R ladder with the given 2R/R ratio,
/// unterminated (the 6581) or terminated by 2R (the 8580), normalised to sum to 1:
/// reSIDfp's `Dac::kinkedDac`, step for step.
pub fn ladder(bits: usize, kink: f64, terminated: bool) -> Vec<f64> {
    const R_INFINITY: f64 = 1e6;
    let mut dac = Vec::with_capacity(bits);
    let mut vsum = 0.0;
    for set_bit in 0..bits {
        let mut vn = 1.0;
        let r = 1.0;
        let r2 = kink * r;
        let mut rn = if terminated { r2 } else { R_INFINITY };
        let mut bit = 0;
        while bit < set_bit {
            rn = if rn == R_INFINITY {
                r + r2
            } else {
                r + (r2 * rn) / (r2 + rn)
            };
            bit += 1;
        }
        if rn == R_INFINITY {
            rn = r2;
        } else {
            rn = (r2 * rn) / (r2 + rn);
            vn = vn * rn / r2;
        }
        bit += 1;
        while bit < bits {
            rn += r;
            let i = vn / rn;
            rn = (r2 * rn) / (r2 + rn);
            vn = rn * i;
            bit += 1;
        }
        dac.push(vn);
        vsum += vn;
    }
    dac.iter().map(|v| v / vsum).collect()
}

/// A ladder's output for `input`: reSIDfp's `Dac::getOutput`.
pub fn output(weights: &[f64], leakage: f64, input: u32, saturate: bool) -> f64 {
    let mut v = 0.0;
    for (i, w) in weights.iter().enumerate() {
        v += if input >> i & 1 != 0 { *w } else { w * leakage };
    }
    if saturate {
        v = SAT_GAIN * v + (1.0 - SAT_GAIN) * SAT * v * v * v;
    }
    v
}

fn float_list(s: &mut String, indent: &str, values: &[f64]) {
    let items: Vec<String> = values.iter().map(|&v| format!("{:e}f", v as f32)).collect();
    for chunk in items.chunks(4) {
        writeln!(s, "{indent}{},", chunk.join(", ")).unwrap();
    }
}

pub fn dac_header() -> Generated {
    let mut s = String::new();
    // REUSE-IgnoreStart
    s.push_str(
        "// SPDX-FileCopyrightText: 2011-2025 Leandro Nini <drfiemost@users.sourceforge.net>\n\
         // SPDX-FileCopyrightText: 2007-2010 Antti Lankila\n\
         // SPDX-FileCopyrightText: 2004,2010 Dag Lem <resid@nimrod.no>\n\
         // SPDX-License-Identifier: GPL-2.0-or-later\n",
    );
    // REUSE-IgnoreEnd
    let kinks: Vec<String> = KINKS.iter().map(|k| format!("{k:.2}")).collect();
    writeln!(
        s,
        "/* Generated by sidou-tablegen; do not edit. To regenerate, from host/:\n\
         \x20*   cargo run --release -p sidou-tablegen\n\
         \x20* Source: reSIDfp (libresidfp {RESIDFP_REV}): Dac::kinkedDac, the R-2R ladder of\n\
         \x20* the waveform (12-bit) and envelope (8-bit) DACs, and the constants\n\
         \x20* SID::setChipModel and FilterModelConfig6581 build the voice output from.\n\
         \x20*\n\
         \x20* The ladder's bit weights (normalised to sum to 1) over a grid of its 2R/R ratio,\n\
         \x20* the \"kink\": {}.\n\
         \x20* reSIDfp's ratios (2.20 for the 6581, 2.00 for the 8580) are grid points;\n\
         \x20* sid_dac_build interpolates between them. Index 0 is the 6581's unterminated\n\
         \x20* ladder, 1 the 8580's, terminated by 2R. {} bytes. */\n\
         #ifndef SIDOU_GEN_DAC_H\n#define SIDOU_GEN_DAC_H\n",
        kinks.join(", "),
        2 * KINKS.len() * (12 + 8) * 4
    )
    .unwrap();
    writeln!(
        s,
        "/* reSIDfp's defaults. */\n\
         #define SID_DAC_KINK_6581 {KINK_6581:.2}f\n\
         #define SID_DAC_KINK_8580 {KINK_8580:.2}f\n\
         /* MOSFET leakage: an off bit still adds this fraction of its weight. */\n\
         #define SID_DAC_LEAKAGE_6581 {LEAKAGE_6581}f\n\
         #define SID_DAC_LEAKAGE_8580 {LEAKAGE_8580}f\n\
         /* The 6581's waveform DAC saturates: v -> GAIN v + (1 - GAIN) SAT v^3. */\n\
         #define SID_DAC_SAT_GAIN {SAT_GAIN}f\n\
         #define SID_DAC_SAT {SAT}f\n\
         /* The waveform DAC input taken as the voice's zero. */\n\
         #define SID_DAC_ZERO_6581 0x{ZERO_6581:x}u\n\
         #define SID_DAC_ZERO_8580 0x{ZERO_8580:x}u\n\
         /* The 6581's voice DC, which follows the envelope DAC: 0.2143 V per unit, over\n\
         \x20* its 1.5 V voice range. (The 8580's is constant: the DC blocker removes it.) */\n\
         #define SID_VOICE_DC_6581 {:e}f\n\
         \n\
         #define SID_DAC_KINKS {}\n\
         #define SID_DAC_KINK_FIRST {:.2}f\n\
         #define SID_DAC_KINK_STEP {:.2}f\n",
        VOICE_DC_6581 as f32,
        KINKS.len(),
        KINKS[0],
        KINKS[1] - KINKS[0],
    )
    .unwrap();
    for (name, bits) in [("WAVE", 12usize), ("ENV", 8)] {
        writeln!(
            s,
            "static const float SID_DAC_{name}_WEIGHTS[2][SID_DAC_KINKS][{bits}] = {{"
        )
        .unwrap();
        for (terminated, label) in [(false, "6581, unterminated"), (true, "8580, terminated")] {
            writeln!(s, "    /* {label} */ {{").unwrap();
            for k in KINKS {
                writeln!(s, "        /* {k:.2} */ {{").unwrap();
                float_list(&mut s, "            ", &ladder(bits, k, terminated));
                writeln!(s, "        }},").unwrap();
            }
            writeln!(s, "    }},").unwrap();
        }
        writeln!(s, "}};\n").unwrap();
    }
    s.push_str("#endif\n");
    Generated {
        path: "core/sid/gen/dac.h",
        contents: s,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use residfp_sys::{dac_table, Model};

    #[test]
    fn the_ladder_reproduces_residfp_at_its_defaults() {
        for (model, kink, leakage, terminated) in [
            (Model::Mos6581, KINK_6581, LEAKAGE_6581, false),
            (Model::Csg8580, KINK_8580, LEAKAGE_8580, true),
        ] {
            for (bits, saturate) in [(12usize, model == Model::Mos6581), (8, false)] {
                let reference = dac_table(model, bits as u32, 1.0, saturate);
                let weights = ladder(bits, kink, terminated);
                for (i, r) in reference.iter().enumerate() {
                    let ours = output(&weights, leakage, i as u32, saturate);
                    assert!(
                        (ours - r).abs() < 1e-12,
                        "{model:?} {bits}-bit, input {i}: {ours} vs reSIDfp {r}"
                    );
                }
            }
        }
    }

    #[test]
    fn the_grid_holds_residfp_defaults() {
        assert!(KINKS.contains(&KINK_6581));
        assert!(KINKS.contains(&KINK_8580));
        for (i, k) in KINKS.iter().enumerate() {
            assert!((k - (KINKS[0] + i as f64 * (KINKS[1] - KINKS[0]))).abs() < 1e-12);
        }
    }
}
